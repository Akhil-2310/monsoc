// Generates packages/sdk/src/generated/{abis,deployments}.ts from Foundry output.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, "contracts/out");
const dest = join(root, "packages/sdk/src/generated");
mkdirSync(dest, { recursive: true });

const contracts = {
  identity: "IdentityRegistry",
  appKeys: "AppKeyRegistry",
  signup: "Signup",
  follows: "FollowGraph",
  feeds: "FeedRegistry",
  payments: "Payments",
  anchor: "Anchor",
  communities: "CommunityRegistry",
  scouts: "ScoutRegistry",
  markets: "CreatorMarkets",
  oracle: "AdminPriceOracle",
  tusd: "TestStable",
  forwarder: "ERC2771Forwarder",
};

let abis = "// Generated by scripts/gen-sdk.mjs. Do not edit.\n\n";
for (const [key, name] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(join(out, `${name}.sol/${name}.json`), "utf8"));
  abis += `export const ${key}Abi = ${JSON.stringify(abi)} as const;\n\n`;
}
writeFileSync(join(dest, "abis.ts"), abis);

const depDir = join(root, "contracts/deployments");
const deployments = {};
if (existsSync(depDir)) {
  for (const f of readdirSync(depDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(depDir, f), "utf8"));
    deployments[d.chainId] = d;
  }
}
writeFileSync(
  join(dest, "deployments.ts"),
  `// Generated by scripts/gen-sdk.mjs. Do not edit.\nimport type { Deployment } from "../types";\n\nexport const deployments: Record<number, Deployment> = ${JSON.stringify(deployments, null, 2)};\n`,
);
console.log(`generated ABIs for ${Object.keys(contracts).length} contracts, deployments for chains: ${Object.keys(deployments).join(", ") || "none"}`);
